"""Scans Fear & Hunger 2: Termina's event data for commands that can conflict with the co-op mod
(party changes, cutscenes moving the player, player-centric checks...).

Usage: python tools/audit_events.py [path/to/www] > report.md
(default path: TERMINA_GAME or C:/Games/Fear2/www). Prints a Markdown report.
"""
import json
import os
import re
import sys
from collections import defaultdict

GAME = (sys.argv[1] if len(sys.argv) > 1 else os.environ.get('TERMINA_GAME', 'C:/Games/Fear2/www')).replace('\\', '/')


def load(name):
    with open(GAME + '/data/' + name, encoding='utf-8') as f:
        return json.load(f)


actors = load('Actors.json')
system = load('System.json')
infos = load('MapInfos.json')


def actor_name(i):
    a = actors[i] if 0 <= i < len(actors) else None
    return (a['name'] if a and a.get('name') else '#%d' % i)


SCRIPT_PATTERNS = {
    'party_script': re.compile(r'(addActor|removeActor|swapOrder|_actors\s*(\.|=|\[))'),
    'player_script': re.compile(r'\$gamePlayer\.(locate|setPosition|reserveTransfer|setTransparent|setDirection|moveStraight|forceMoveRoute|jump)'),
    'input_script': re.compile(r'Input\.(isPressed|isTriggered|isRepeated|isLongPressed)'),
}

# categoria -> lista de (sitio, detalle)
hits = defaultdict(list)


def scan_list(where, lst):
    for cmd in lst:
        c, p = cmd['code'], cmd['parameters']
        if c == 129:
            op = 'add' if p[1] == 0 else 'remove'
            hits['party_change'].append((where, '%s %s' % (op, actor_name(p[0]))))
        elif c == 205 and p[0] == -1:
            hits['player_move_route'].append((where, ''))
        elif c == 211:
            hits['player_transparency'].append((where, 'ON' if p[0] == 0 else 'OFF'))
        elif c == 204:
            hits['scroll_map'].append((where, ''))
        elif c in (212, 213) and p[0] == -1:
            hits['fx_on_player'].append((where, 'animation' if c == 212 else 'balloon'))
        elif c == 122 and p[3] == 3 and p[4] == 5 and p[5] == -1:
            what = ['x', 'y', 'direction', 'screen x', 'screen y'][p[6]] if p[6] < 5 else str(p[6])
            hits['var_from_player'].append((where, what))
        elif c == 111 and p[0] == 6 and p[1] == -1:
            hits['cond_player_direction'].append((where, ''))
        elif c == 111 and p[0] == 11:
            hits['cond_button'].append((where, str(p[1])))
        elif c == 285 and p[1] == 0:
            hits['location_info'].append((where, ''))
        elif c in (353, 354):
            hits['game_over_title'].append((where, 'game over' if c == 353 else 'title'))
        elif c in (355, 655, 111) and c != 111 or (c == 111 and p[0] == 12):
            text = p[0] if c != 111 else p[1]
            if not isinstance(text, str):
                continue
            for key, rx in SCRIPT_PATTERNS.items():
                if rx.search(text):
                    hits[key].append((where, text.strip()[:90]))


def page_where(kind, name, ev_name, ev_id, page):
    return '%s | %s (EV%03d) p%d' % (name, ev_name, ev_id, page + 1)


map_files = sorted(f for f in os.listdir(GAME + '/data') if re.match(r'Map\d{3}\.json$', f))
for f in map_files:
    mid = int(f[3:6])
    info = infos[mid] if mid < len(infos) else None
    mname = 'Map%03d %s' % (mid, info['name'] if info else '')
    data = load(f)
    for ev in data['events']:
        if not ev:
            continue
        for pi, page in enumerate(ev['pages']):
            scan_list(page_where('map', mname, ev['name'], ev['id'], pi), page['list'])

for ce in load('CommonEvents.json'):
    if ce:
        scan_list('Common %d %s' % (ce['id'], ce['name']), ce['list'])

for tr in load('Troops.json'):
    if not tr:
        continue
    for pi, page in enumerate(tr['pages']):
        scan_list('Troop %d %s p%d' % (tr['id'], tr['name'], pi + 1), page['list'])

TITLES = {
    'party_change': 'Party changes (Change Party Member)',
    'party_script': 'Party changes by script',
    'player_move_route': 'Move routes on the player (cutscenes)',
    'player_script': 'Scripts moving / hiding the player',
    'player_transparency': 'Player transparency',
    'scroll_map': 'Scroll map (camera moves in cutscenes)',
    'fx_on_player': 'Animations / balloons on the player',
    'var_from_player': 'Variables read from the player (position / direction)',
    'cond_player_direction': 'Conditions on the player direction',
    'location_info': 'Get Location Info',
    'cond_button': 'Conditions on a pressed button',
    'input_script': 'Scripts reading Input',
    'game_over_title': 'Game over / return to title',
}

print('# Termina event audit\n')
print('Generated by `tools/audit_events.py` from the game data (%d maps).\n' % len(map_files))
print('| Category | Commands | Places (maps / common events / troops) |')
print('|---|---|---|')
for key in TITLES:
    places = {w.split(' | ')[0] for w, _ in hits[key]}
    print('| %s | %d | %d |' % (TITLES[key], len(hits[key]), len(places)))
print()
for key in TITLES:
    rows = hits[key]
    if not rows:
        continue
    print('## %s (%d)\n' % (TITLES[key], len(rows)))
    by_place = defaultdict(list)
    for w, d in rows:
        by_place[w.split(' | ')[0]].append((w, d))
    for place in sorted(by_place, key=lambda k: -len(by_place[k]))[:40]:
        items = by_place[place]
        details = sorted({d for _, d in items if d})
        print('- **%s**: %d%s' % (place, len(items), (' (' + ', '.join(details[:6]) + ('...' if len(details) > 6 else '') + ')') if details else ''))
    if len(by_place) > 40:
        print('- ... and %d more places' % (len(by_place) - 40))
    print()
